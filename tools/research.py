"""Metadata-only local CLI. Licensed market data never enters this directory."""
from pathlib import Path
import argparse
import hashlib
import json
import os
import pprint
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT / "cloud"))
from qresearch.artifacts import FilesystemArtifactStore, canonical_json
from qresearch.registry import Registry
from qresearch.deployment_sources import SOURCE_IDENTITY_POLICY, build_manifest


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def source_digest(path):
    return hashlib.sha256(path.read_text(encoding="utf-8-sig").encode("utf-8")).hexdigest()


def write_changed(path, data):
    payload = data if isinstance(data, bytes) else data.encode("utf-8")
    if path.exists() and path.read_bytes() == payload:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    with temporary.open("wb") as stream:
        stream.write(payload)
        stream.flush()
        os.fsync(stream.fileno())
    os.replace(temporary, path)
    return True


def configuration():
    documents = {name: read_json(ROOT / "config" / (name + ".json"))
                 for name in ("research", "universe", "data", "workflow", "budget")}
    # Historical source fixtures without this file retain their old identity.
    # New policy selection is semantic configuration, never an execution grant.
    policy_path = ROOT / "config" / "deployment.json"
    if policy_path.exists():
        policy = read_json(policy_path)
        if (type(policy) is not dict
                or set(policy) != {"schema_version", "manifest_schema_version", "source_identity_policy"}
                or type(policy["schema_version"]) is not int or policy["schema_version"] != 1
                or type(policy["manifest_schema_version"]) is not int or policy["manifest_schema_version"] != 2
                or policy["source_identity_policy"] != SOURCE_IDENTITY_POLICY):
            raise ValueError("Unsupported explicit deployment source policy") from None
        documents["deployment"] = policy
    return {name: value for name, value in documents.items() if name != "budget"} | {
        "configuration_id": documents["research"]["configuration_id"],
        "budget_limits": documents["budget"]["limits"],
        "budget_allocations": documents["budget"]["allocations"],
        "active_factor": documents["research"]["active_factor_spec"],
        "active_model": documents["research"]["active_model_spec"],
        "active_trading_rules": documents["research"]["active_trading_spec"]}


def build():
    config = configuration()
    source_hash = hashlib.sha256(canonical_json(config)).hexdigest()
    implementation = {path.name: source_digest(path)
                      for path in sorted((ROOT / "cloud" / "qresearch").glob("*.py"))}
    implementation_hash = hashlib.sha256(canonical_json(implementation)).hexdigest()
    text = ("# Generated by tools/research.py build. Edit config/*.json only.\n"
            + "SOURCE_SHA256 = " + repr(source_hash) + "\nIMPLEMENTATION_SHA256 = " + repr(implementation_hash) + "\nCONFIGURATION = "
            + pprint.pformat(config, sort_dicts=True, width=110) + "\n")
    changed = write_changed(ROOT / "cloud" / "research_config.py", text)
    generated = {"_engineering_task_input.py", "_collection_task_input.py"} if "deployment" in config else set()
    sources = {path.relative_to(ROOT / "cloud").as_posix(): path.read_bytes()
               for path in sorted((ROOT / "cloud").rglob("*.py"))
               if "__pycache__" not in path.parts and path.relative_to(ROOT / "cloud").as_posix() not in generated}
    from qresearch.deployment_sources import source_sha256
    files = {name: source_sha256(raw) for name, raw in sources.items()}
    deployment = {"configuration_hash": source_hash,
                  "implementation_hash": implementation_hash, "source_hash_policy": "UTF-8 with normalized LF line endings",
                  "source_files": files}
    if "deployment" in config:
        deployment["deployment_manifest"] = build_manifest(sources)
    write_changed(ROOT / "audit" / "deployment.json", json.dumps(deployment, indent=2, sort_keys=True) + "\n")
    return {"config_changed": changed, "configuration_hash": source_hash, "source_files": len(files)}


def open_registry():
    store = FilesystemArtifactStore(ROOT / "audit" / "runtime")
    baseline_key = "registry/baseline.json"
    store.write_once(baseline_key, canonical_json(read_json(ROOT / "config" / "budget.json"))) if not store.exists(baseline_key) else None
    baseline = json.loads(store.read_bytes(baseline_key))
    return Registry(store, baseline)


def export_usage(registry):
    path = ROOT / "config" / "budget.json"
    budget = read_json(path)
    usage = registry.snapshot()["usage"]
    keys = {"configurations": ("configuration_budget_charges", "configuration_normal_used", "configuration_reserve_used"),
            "research": ("research_execution_attempts", "research_normal_used", "research_reserve_used"),
            "lean": ("lean_submission_attempts", "lean_normal_used", "lean_reserve_used")}
    for stage, fields in keys.items():
        for field, part in zip(fields, ("total", "normal", "reserve")):
            budget["usage"][field] = usage[stage][part]
    cycle = registry.configuration_cycle_snapshot()
    if cycle["sequence"] > 0:
        budget["configuration_cycle"] = cycle
    write_changed(path, json.dumps(budget, ensure_ascii=False, indent=2) + "\n")


def existing_config(registry):
    key = "migration/authorized-configurations.jsonl"
    if not registry.store.exists(key):
        registry.store.write_once(key, (ROOT / "audit" / "configurations.jsonl").read_bytes())
    source = registry.store.read_bytes(key)
    return registry.import_existing_config(configuration(), source_reference={"key": key,
           "sha256": hashlib.sha256(source).hexdigest(), "configuration_id": "GENERIC-WF-001"})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("build", "status", "bootstrap", "register", "begin", "pending", "complete", "fail", "ambiguous"))
    parser.add_argument("--stage", choices=("research", "lean"), default="research")
    parser.add_argument("--operation")
    parser.add_argument("--allocation", choices=("normal", "reserve"), default="normal")
    parser.add_argument("--attempt")
    parser.add_argument("--external-id")
    parser.add_argument("--result-file", type=Path)
    parser.add_argument("--config-file", type=Path)
    parser.add_argument("--config-id")
    parser.add_argument("--reason")
    parser.add_argument("--retry-of")
    args = parser.parse_args()
    if args.command == "build":
        print(json.dumps(build()))
        return
    registry = open_registry()
    if args.command == "bootstrap":
        config_id = existing_config(registry)
        result = {"configuration_id": config_id}
    elif args.command == "register":
        if not args.config_file:
            parser.error("--config-file with the complete frozen economic/implementation configuration is required")
        full_config = read_json(args.config_file)
        result = {"configuration_id": registry.register_config(full_config, allocation=args.allocation)}
    elif args.command == "status":
        from qresearch.runtime import readiness
        result = registry.snapshot() | {"readiness": readiness(configuration())}
    elif args.command == "begin":
        if not args.operation:
            parser.error("--operation must be a stable logical key")
        config_id = args.config_id or existing_config(registry)
        attempt = registry.begin_attempt(config_id, args.stage, allocation=args.allocation,
                                         operation_key=args.operation, retry_of=args.retry_of, reason=args.reason)
        result = vars(attempt)
    elif args.command == "complete":
        if not args.result_file:
            parser.error("--result-file with checked completion metadata is required")
        result = vars(registry.complete(args.attempt, read_json(args.result_file), external_id=args.external_id))
    elif args.command == "fail":
        result = vars(registry.fail(args.attempt, args.reason or "Execution failed"))
    elif args.command == "pending":
        if not args.external_id:
            parser.error("--external-id is required for an observed asynchronous submission")
        result = vars(registry.pending(args.attempt, external_id=args.external_id))
    else:
        result = vars(registry.ambiguous(args.attempt, reason=args.reason or "External outcome unknown"))
    export_usage(registry)
    print(json.dumps(result, ensure_ascii=True))


if __name__ == "__main__":
    main()
