"""RC003 end-to-end adapter checks against a synthetic LEAN date-file model.

The model transcribes the public18207 NY==NY source-date enumeration and the
strict start < EndTime <= end filter. Artificial weekday files contain one
item; no provider, SDK, real SID, price, financial value or holiday data is used.
Expected snapshot clocks below are hand-listed, not generated by the adapter.
"""
from datetime import date, datetime, time, timedelta
from pathlib import Path
from types import SimpleNamespace as NS
import sys
import unittest

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "cloud"))
from qresearch.artifacts import MemoryArtifactStore
from qresearch.collection import CollectionError, CollectionInterrupted, HistoricalCollectionPlan, HistoricalSnapshotCollector
from qresearch.historical_source import HistoricalSourceError, QuantConnectSnapshotSource, _history_endpoint, _history_start
from test_historical_source import FakeQB, native, response, ts


CATALOG = {"dollar_volume": {"kind": "number", "role": "synthetic_liquidity", "unit": "synthetic", "period_accessor": None}}


def regular_open(start, end):
    if start.weekday() >= 5:
        return False
    return (start < datetime.combine(start.date(), time(16))
            and end > datetime.combine(start.date(), time(9, 30)))


class SourceDateQB(FakeQB):
    def __init__(self, source_dates, *, frontier=datetime(2019, 1, 1)):
        super().__init__()
        self.time = frontier
        self.source_dates = set(source_dates)

    def universe_history(self, universe, start, end, *, flatten):
        self.calls.append((universe, start, end, flatten))
        if start.tzinfo is not None or end.tzinfo is not None or flatten is not False:
            raise AssertionError("Native dates must be naive NY and nonflattened")
        # LEAN Common/Time.cs retains the exact first-day start rather than
        # rounding it down. Later source dates start at local midnight.
        current = start
        thru = datetime.combine(end.date() + timedelta(days=1), time())
        stamps = []
        while current < thru:
            eod = datetime.combine(current.date() + timedelta(days=1), time())
            if regular_open(current, eod) and current.date() in self.source_dates:
                end_time = eod  # Fundamental source-date d has modeled EndTime d+1.
                if start < end_time <= end:
                    stamps.append(end_time)
            current = eod
        if not stamps:
            return pd.DataFrame()  # The actual SDK's observed empty sentinel.
        index = pd.MultiIndex.from_tuples([(universe, stamp) for stamp in stamps], names=["symbol", "time"])
        return pd.Series([[NS(symbol=NS(id="SYNTHETIC-RC003-SID"), dollar_volume=1)] for stamp in stamps],
                         index=index, dtype=object)


class HistorySourceDateGridTests(unittest.TestCase):
    def source(self, qb):
        return QuantConnectSnapshotSource(qb, CATALOG, api=NS(Resolution=NS(DAILY="synthetic_daily")))

    def fetch(self, qb, start="2018-01-09", end="2018-01-10"):
        return list(self.source(qb).fetch(ts(start), ts(end), CATALOG))

    def clocks(self, rows):
        return [pd.Timestamp(row["snapshot_at"]).tz_localize(None).isoformat() for row in rows]

    def plan(self, start, end, *, days=1):
        return HistoricalCollectionPlan.from_dict(dict(schema_version=1, plan_id="SYNTHETIC-RC003-REPAIR",
            scope="engineering", source="quantconnect_fundamental_universe", data_version="SYNTHETIC-RC003-v4",
            start=ts(start).isoformat(), end_exclusive=ts(end).isoformat(), timezone="America/New_York",
            fields=list(CATALOG), calendar_days_per_request=days, max_batch_records=2,
            max_records_per_window=20, source_manifest_hash="e" * 64), field_catalog=CATALOG)

    def test_present_prior_source_file_now_yields_known_target_snapshot(self):
        qb = SourceDateQB([date(2018, 1, 8), date(2018, 1, 9)])
        # This independent source model shows the old pair of endpoints loses
        # a guaranteed record before testing the repaired adapter.
        old = qb.universe_history("SYNTHETIC", _history_endpoint(ts("2018-01-09")),
            _history_endpoint(ts("2018-01-10")), flatten=False)
        self.assertTrue(old.empty)
        qb.calls.clear()
        rows = self.fetch(qb)
        self.assertEqual(self.clocks(rows), ["2018-01-09T00:00:00"])
        self.assertEqual(qb.calls[0][1:3], (datetime(2018, 1, 8), datetime(2018, 1, 9, 23, 59, 59, 999999)))

    def test_seven_day_chunk_keeps_first_snapshot_and_excludes_upper_endpoint(self):
        files = [date(2018, 1, day) for day in (8, 9, 10, 11, 12, 15)]
        rows = self.fetch(SourceDateQB(files), "2018-01-09", "2018-01-16")
        self.assertEqual(self.clocks(rows), ["2018-01-09T00:00:00", "2018-01-10T00:00:00",
            "2018-01-11T00:00:00", "2018-01-12T00:00:00", "2018-01-13T00:00:00"])

    def test_forty_daily_windows_recover_hand_listed_records_and_cache_only_replay(self):
        files = [date(2017, 12, 31) + timedelta(days=i) for i in range(41)]
        qb, store = SourceDateQB(files), MemoryArtifactStore()
        source, plan = self.source(qb), self.plan("2018-01-01", "2018-02-10")
        collector = HistoricalSnapshotCollector(store, source, plan, synthetic=True)
        first = collector.collect()
        rows = [row for ref in first["window_refs"] for row in collector.read_window(ref)]
        expected = ["2018-01-02", "2018-01-03", "2018-01-04", "2018-01-05", "2018-01-06",
            "2018-01-09", "2018-01-10", "2018-01-11", "2018-01-12", "2018-01-13",
            "2018-01-16", "2018-01-17", "2018-01-18", "2018-01-19", "2018-01-20",
            "2018-01-23", "2018-01-24", "2018-01-25", "2018-01-26", "2018-01-27",
            "2018-01-30", "2018-01-31", "2018-02-01", "2018-02-02", "2018-02-03",
            "2018-02-06", "2018-02-07", "2018-02-08", "2018-02-09"]
        self.assertEqual(self.clocks(rows), [value + "T00:00:00" for value in expected])
        self.assertEqual((first["window_count"], first["record_count"], first["empty_windows"]), (40, 29, 11))
        self.assertEqual(len(qb.calls), 40)
        replay = HistoricalSnapshotCollector(store, None, plan, synthetic=True).collect()
        self.assertEqual((replay["provider_calls"], replay["reused_windows"]), (0, 40))
        self.assertEqual(first["window_refs"], replay["window_refs"])
        self.assertEqual(len(qb.calls), 40)
        for flag in ("full_historical_US200_certified", "actual_availability_certified", "research_certified"):
            self.assertIs(first[flag], False)

    def test_adjacent_seven_day_chunks_do_not_duplicate_snapshot_clocks(self):
        qb = SourceDateQB([date(2018, 1, 8) + timedelta(days=i) for i in range(15)])
        store, plan = MemoryArtifactStore(), self.plan("2018-01-09", "2018-01-23", days=7)
        collector = HistoricalSnapshotCollector(store, self.source(qb), plan, synthetic=True)
        receipt = collector.collect()
        rows = [row for ref in receipt["window_refs"] for row in collector.read_window(ref)]
        expected_days = (9, 10, 11, 12, 13, 16, 17, 18, 19, 20)
        self.assertEqual(self.clocks(rows), ["2018-01-%02dT00:00:00" % day for day in expected_days])
        self.assertEqual(len(qb.calls), 2)

    def test_source_day_absence_never_uses_next_file_or_backfills(self):
        qb = SourceDateQB([date(2018, 1, 9)])  # Jan8 file is deliberately absent.
        source = self.source(qb)
        self.assertEqual(list(source.fetch(ts("2018-01-09"), ts("2018-01-10"), CATALOG)), [])
        self.assertEqual(source.history_call_count, 1)
        self.assertFalse(source.provenance()["actual_availability_certified"])

    def test_weekend_snapshots_are_not_relabelled_as_monday(self):
        files = [date(2018, 1, 5)]
        self.assertEqual(self.fetch(SourceDateQB(files), "2018-01-08", "2018-01-09"), [])
        rows = self.fetch(SourceDateQB(files), "2018-01-06", "2018-01-09")
        self.assertEqual(self.clocks(rows), ["2018-01-06T00:00:00"])

    def test_calendar_lookback_preserves_midnight_through_both_dst_changes(self):
        for logical, prior, total_hours in (("2018-03-12", datetime(2018, 3, 11), 47),
                                            ("2018-11-05", datetime(2018, 11, 4), 49)):
            with self.subTest(logical=logical):
                start = ts(logical)
                end = start + pd.DateOffset(days=1)
                self.assertEqual(_history_start(start), prior)
                self.assertEqual(_history_start(start.tz_convert("UTC")), prior)
                qb = FakeQB(response([native()], logical))
                qb.time = end.tz_localize(None).to_pydatetime()
                rows = list(self.source(qb).fetch(start, end, CATALOG))
                self.assertEqual(len(rows), 1)
                left, right = qb.calls[0][1:3]
                self.assertEqual(left, prior)
                elapsed = (pd.Timestamp(right).tz_localize("America/New_York").tz_convert("UTC")
                    - pd.Timestamp(left).tz_localize("America/New_York").tz_convert("UTC"))
                self.assertEqual(elapsed, pd.Timedelta(hours=total_hours) - pd.Timedelta(microseconds=1))

    def test_expanded_window_crops_before_sid_container_or_value_projection(self):
        class ForbiddenProjection:
            def __getattribute__(self, name):
                raise AssertionError("LICENSED outside-window field was accessed")
        outside = response(ForbiddenProjection(), "2018-01-08 12:00")
        inside = response([NS(symbol=NS(id="SYNTHETIC"), dollar_volume=1)], "2018-01-09")
        qb = FakeQB(pd.concat([outside, inside]))
        qb.time = datetime(2018, 1, 10)
        self.assertEqual(self.clocks(self.fetch(qb)), ["2018-01-09T00:00:00"])

    def test_wrong_universe_clock_and_duplicate_are_checked_before_cropping(self):
        valid = response([], "2018-01-08 12:00")
        wrong_universe = valid.copy()
        wrong_universe.index = pd.MultiIndex.from_tuples([("WRONG", pd.Timestamp("2018-01-08 12:00"))], names=["symbol", "time"])
        fixtures = [pd.concat([valid, wrong_universe]), pd.concat([valid, valid]),
            response([], "2018-01-08"), response([], "2018-01-07 23:59"),
            response([], "2018-01-10"), response([], "2024-01-01"),
            response([], "2018-01-09 23:59:59.999999500")]
        for data in fixtures:
            with self.subTest(index=list(data.index)):
                qb = FakeQB(data)
                qb.time = datetime(2018, 1, 10)
                with self.assertRaises(HistoricalSourceError):
                    self.fetch(qb)

    def test_failed_future_response_keeps_intent_and_cannot_trigger_automatic_refetch(self):
        qb = FakeQB(response([], "2024-01-01"))
        qb.time = datetime(2018, 1, 10)
        source, store, plan = self.source(qb), MemoryArtifactStore(), self.plan("2018-01-09", "2018-01-10")
        collector = HistoricalSnapshotCollector(store, source, plan, synthetic=True)
        with self.assertRaises(CollectionError):
            collector.collect()
        before = dict(store._data)
        with self.assertRaises(CollectionInterrupted):
            collector.collect()
        self.assertEqual(store._data, before)
        self.assertEqual(source.history_call_count, 1)
        self.assertEqual(len(qb.calls), 1)

    def test_final_request_is_rejected_without_any_native_history(self):
        qb = SourceDateQB([date(2023, 12, 29)], frontier=datetime(2024, 1, 1))
        with self.assertRaises(HistoricalSourceError):
            self.fetch(qb, "2024-01-01", "2024-01-02")
        self.assertEqual(qb.calls, [])


if __name__ == "__main__":
    unittest.main()
